// Dump pydantic JSON schemas (src/econ/schemas.py) -> web/schema/*.json -> web/src/types/*.ts
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, readdirSync } from "node:fs";
import { compile } from "json-schema-to-typescript";
import { fileURLToPath } from "node:url";
import path from "node:path";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const root = path.resolve(web, "..");
const py = process.env.PYTHON || "python";
const out = execFileSync(
  py,
  ["-c", "import json,sys;sys.path.insert(0,'src');from econ.schemas import json_schema;sys.stdout.buffer.write(json.dumps(json_schema()).encode())"],
  { cwd: root, maxBuffer: 1 << 26 },
).toString("utf8");
const schemas = JSON.parse(out);
mkdirSync(path.join(web, "schema"), { recursive: true });
mkdirSync(path.join(web, "src/types"), { recursive: true });
for (const [name, schema] of Object.entries(schemas)) {
  writeFileSync(path.join(web, "schema", `${name}.json`), JSON.stringify(schema, null, 2));
  const ts = await compile(schema, name, { bannerComment: "/* GENERATED by npm run gen:types - do not edit */", additionalProperties: false });
  writeFileSync(path.join(web, "src/types", `${name}.ts`), ts);
}
const names = readdirSync(path.join(web, "src/types")).filter((f) => f.endsWith(".ts") && f !== "index.ts");
console.log("generated", names.join(", "));
