"""`econ codemap`: regenerate docs/CODEMAP.md - one line per module (docstring summary) + its public functions.

Agents read CODEMAP instead of globbing/grepping the repo. `--check` exits 2 when the file is stale (CI).
"""
from __future__ import annotations

import ast
from pathlib import Path

from .common import DOCS, ROOT, Result, rel

SCAN = [("src/econ", ("*.py",)), ("tests", ("*.py",)), ("web/src", ("*.ts", "*.tsx"))]
OTHER = ["config/*.yaml", "config/*.json", ".github/workflows/*.yml"]
MAX_FUNCS = 8


def _py_line(p: Path) -> str:
    try:
        tree = ast.parse(p.read_text(encoding="utf-8"))
    except SyntaxError:
        return f"- `{rel(p)}` (syntax error)"
    doc = (ast.get_docstring(tree) or "").strip().splitlines()
    names = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))
             and not n.name.startswith("_") and not n.name.startswith("test_")]
    tests = sum(1 for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_"))
    tail = (f" · {tests} tests" if tests else "") + (
        f" · {', '.join(names[:MAX_FUNCS])}{' …' if len(names) > MAX_FUNCS else ''}" if names else "")
    return f"- `{rel(p)}` {doc[0] if doc else ''}{tail}"


def _ts_line(p: Path) -> str:
    first = next((ln.strip(" /*") for ln in p.read_text(encoding="utf-8").splitlines()[:3]
                  if ln.strip().startswith(("//", "/*"))), "")
    return f"- `{rel(p)}` {first}"


def render() -> str:
    out = ["# Code map (generated by `python econ.py codemap` - do not edit by hand)", "",
           "Find code here instead of Glob/Grep over the repo. Architecture and decisions: docs/ARCHITECTURE.md.", ""]
    for base, pats in SCAN:
        files = sorted(p for pat in pats for p in (ROOT / base).rglob(pat) if "__pycache__" not in p.parts
                       and "node_modules" not in p.parts and p.name != "__init__.py")
        if not files:
            continue
        out += [f"## {base}", ""]
        out += [_py_line(p) if p.suffix == ".py" else _ts_line(p) for p in files]
        out.append("")
    cfgs = sorted({p for g in OTHER for p in ROOT.glob(g)})
    if cfgs:
        out += ["## config & CI", "", *[f"- `{rel(p)}`" for p in cfgs], ""]
    return "\n".join(out).rstrip() + "\n"


def run(args) -> Result:
    target = DOCS / "CODEMAP.md"
    text = render()
    old = target.read_text(encoding="utf-8") if target.exists() else ""
    if getattr(args, "check", False):
        stale = old != text
        return Result("CODEMAP stale - run `python econ.py codemap`" if stale else "CODEMAP up to date",
                      {"stale": stale}, code=2 if stale else 0)
    if old != text:
        DOCS.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return Result(f"docs/CODEMAP.md: {len(text.splitlines())} lines" + ("" if old != text else " (unchanged)"))
